! No-op GSAF graphics entries for equ_nogr, the equ program linked
! without GSAF (make -C equ equ_nogr). The library comparison
! (python/equlib/tests/test_program_parity.py) runs this program on the
! same input as libequapi.so and compares the two G-EQDSK files. The
! menu commands it is given (R, E, Q) draw nothing; GSOPEN here reads
! nothing from standard input, where the GSAF one asks for a display.
!
! The list is the set of GSAF symbols that equmain.o, libequ.a, libgrf.a
! and libtask.a leave undefined when linked without GSAF (measured with
! the link of 2026-11-22). Form as eq/eq_static_stubs.f90: two functions
! whose values the callers use, and subroutines without arguments
! (resolved by name; the callers' arguments are ignored).
!
! Never linked into libequapi.so, which contains no graphics code.

